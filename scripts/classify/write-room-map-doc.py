#!/usr/bin/env python3
"""Render docs/ROOM-MAP.md from room-map.json. Pure formatting -- every number here
came from build-room-map.py, which derived it from the corpus."""
import json, os, sys, argparse
from collections import defaultdict

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
ap = argparse.ArgumentParser()
ap.add_argument("--rooms", default=f"{ROOT}/data/classify/room-map.json")
ap.add_argument("--before", default=f"{ROOT}/data/classify/room-map-observed-only.json")
ap.add_argument("--out", default=f"{ROOT}/docs/ROOM-MAP.md")
ap.add_argument("--provisional", action="store_true")
ap.add_argument("--labeller", default="knn-bge-m3-k15")
A = ap.parse_args()

d = json.load(open(A.rooms))
before = json.load(open(A.before)) if os.path.exists(A.before) else None
rooms = d["rooms"]
by_cat = defaultdict(list)
for r in rooms: by_cat[r["category"]].append(r)
sizes = sorted((r["n"] for r in rooms), reverse=True)

L = []
w = L.append
w("# The room map")
w("")
w(f"Generated by `scripts/classify/build-room-map.py` from a corpus of **{d['corpus']:,}** papers.")
w(f"Room ceiling **{d['max_room']:,}**" + (" — **provisional**: D9 (LANE-CURVE) has not run, so this is "
  "the brief's placeholder, not a measured ceiling. Re-run this script with `--max-room N` once "
  "`docs/HAYSTACK-CURVE.md` exists." if A.provisional else "") + "")
w("")
w("A **room** is a scoped haystack a subject agent searches. The bet is that our stack wins inside")
w("small rooms (see `docs/BEDROCK-KB-BAKEOFF.md`), so every room must come in under the ceiling.")
w("This is **not** a query-time router — the user's navigation choice is the router.")
w("")
w("## Headline")
w("")
w("| | |")
w("|---|---|")
w(f"| rooms | **{len(rooms):,}** |")
w(f"| papers placed | **{d['placed']:,}** |")
w(f"| papers without a room | **{d['unplaced']:,}** |")
w(f"| largest room | {sizes[0]:,} |")
w(f"| median room | {sizes[len(sizes)//2]:,} |")
w(f"| smallest room | {sizes[-1]:,} |")
w(f"| rooms over the ceiling | {sum(1 for s in sizes if s > d['max_room'])} |")
w(f"| rooms relying on a predicted label for ≥50% of members | "
  f"{sum(1 for r in rooms if r['n'] and r['n_predicted_labels']/r['n'] >= 0.5):,} |")
w("")
if before:
    w("### What the predicted labels bought")
    w("")
    w("Both configurations place every paper, so \"papers without a room\" is zero either way and")
    w("says nothing. The real gain is **which axis** a paper is placed on: a room split by MeSH")
    w("subtree is a topic a researcher can choose; a room split by year is a filing cabinet.")
    w("")
    def axis_papers(doc):
        acc = defaultdict(int)
        for r in doc["rooms"]: acc[r["axis"]] += r["n"]
        return acc
    ab, aa = axis_papers(before), axis_papers(d)
    w("| axis | papers, observed MeSH only | papers, + predicted | change |")
    w("|---|---|---|---|")
    for k in ["mesh", "category", "year", "no-mesh-facet", "residual"]:
        if not (ab[k] or aa[k]): continue
        w(f"| `{k}` | {ab[k]:,} | {aa[k]:,} | {aa[k]-ab[k]:+,} |")
    w("")
    w(f"Rooms rose {len(before['rooms']):,} → {len(rooms):,}: papers that previously fell into a few")
    w("huge undifferentiated year buckets now separate into named topics.")
    w("")
w("## Calibration — predicted labels are not observed labels")
w("")
w(f"{d['n_predicted']:,} papers carry a **predicted** MeSH tag from `{A.labeller}` rather than an")
w("NLM-assigned one. They live in a separate table (`preprint_mesh_predicted`), every row carries")
w("its probability and the model id, and observed MeSH is never overwritten.")
w("")
w("**The labeller is kNN propagation over stock bge-m3 embeddings, NOT cshl-MESH-tagger.**")
w("The tagger was trained, scored, and lost to that baseline on every ranking metric")
w("(P@5 58.68 vs 63.39, R@15 52.66 vs 61.82 on the full held-out test split), so using it here")
w("would have meant labelling the corpus with the arm measured to be worse. Both arms are")
w("loaded in `preprint_mesh_predicted`, distinguished by `model`, so the choice is reversible")
w("and auditable. The `predicted` column")
w("below is how many of a room's members were placed using a predicted label — a room at 100% is a")
w("room whose very existence is a model's opinion, and should be read that way.")
w("")
w("## Axes used")
w("")
axes = defaultdict(int)
for r in rooms: axes[r["axis"]] += 1
w("| axis | rooms | meaning |")
w("|---|---|---|")
mean = {"category": "the category was already under the ceiling — no split needed",
        "mesh": "split on a MeSH tree subtree (the preferred axis)",
        "year": "MeSH could not split it; fell back to a year band",
        "no-mesh-facet": "members carry no topical MeSH descriptor",
        "residual": "sub-threshold slivers merged so we do not ship 40-paper rooms"}
for k, v in sorted(axes.items(), key=lambda kv: -kv[1]):
    w(f"| `{k}` | {v} | {mean.get(k,'')} |")
w("")
if d["unplaced"]:
    w("## Papers without a room")
    w("")
    w("| category | facet | years | papers |")
    w("|---|---|---|---|")
    for u in sorted(d.get("unplaced_groups",[]), key=lambda x: -x["n"]):
        w(f"| {u['category']} | `{u.get('facet','')}` | {u.get('years','')} | {u['n']:,} |")
    w("")
else:
    w("## Papers without a room: **zero**")
    w("")
    w("Every paper in the corpus is in exactly one room. Rooms are a partition, not an overlay —")
    w("so this count is meaningful rather than an artefact of double-counting.")
    w("")
w("## The rooms")
w("")
for c, rs in sorted(by_cat.items(), key=lambda kv: -sum(r["n"] for r in kv[1])):
    tot = sum(r["n"] for r in rs)
    w(f"### {c} — {tot:,} papers in {len(rs)} room{'s' if len(rs)!=1 else ''}")
    w("")
    w("| room | papers | axis | predicted |")
    w("|---|---|---|---|")
    for r in sorted(rs, key=lambda r: -r["n"]):
        pct = f"{100*r['n_predicted_labels']/r['n']:.0f}%" if r["n"] else "—"
        w(f"| {r['name']} | {r['n']:,} | `{r['axis']}` | {pct} |")
    w("")
open(A.out, "w").write("\n".join(L) + "\n")
print(f"wrote {A.out} ({len(rooms)} rooms)")
